"""Download the UCI processed Cleveland heart-disease dataset."""

from __future__ import annotations

import csv
from datetime import date
from io import StringIO
from pathlib import Path
from urllib.request import urlopen

DATASET_URL = (
    "https://archive.ics.uci.edu/ml/machine-learning-databases/heart-disease/"
    "processed.cleveland.data"
)
ROOT = Path(__file__).resolve().parents[2]
RAW_PATH = ROOT / "data" / "raw" / "processed.cleveland.data"
POINTER_PATH = ROOT / "data" / "raw" / "README.md"
EXPECTED_COLUMNS = 14
AUTHOR = "2025ae05142"


def download_dataset() -> Path:
    """Fetch and validate the source file before writing it to the raw-data directory."""
    with urlopen(DATASET_URL, timeout=30) as response:
        content = response.read().decode("utf-8")

    rows = list(csv.reader(StringIO(content)))
    if not rows or any(len(row) != EXPECTED_COLUMNS for row in rows):
        raise ValueError(
            f"Unexpected dataset shape: expected {EXPECTED_COLUMNS} columns per row"
        )

    RAW_PATH.parent.mkdir(parents=True, exist_ok=True)
    RAW_PATH.write_text(content, encoding="utf-8")
    POINTER_PATH.write_text(
        "# Raw dataset pointer\n\n"
        f"- Source: {DATASET_URL}\n"
        f"- Downloaded: {date.today().isoformat()}\n"
        f"- Local file: `{RAW_PATH.name}`\n"
        f"- Author: `{AUTHOR}`\n"
        "- The file is generated by `python src/data/download_heart.py`.\n",
        encoding="utf-8",
    )
    return RAW_PATH


if __name__ == "__main__":
    print(f"Downloaded {download_dataset()} (Author: {AUTHOR})")
